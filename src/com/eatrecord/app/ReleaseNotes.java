    static String latestVersion() { return HISTORY.length == 0 ? "" : versionOf(HISTORY[HISTORY.length - 1]); }

    static List<String> versions() {
        List<String> result = new ArrayList<>();
        for (String[] group : HISTORY) result.add(versionOf(group));
        return result;
    }

    static boolean contains(String version) { return indexOf(version) >= 0; }

    static String currentText(String version) {
        int index = indexOf(version);
        if (index >= 0) return groupText(HISTORY[index]);
        String installed = version == null ? "" : version.trim();
        return (installed.isEmpty() ? "当前版本" : installed)
                + "\n• 此版本的更新说明暂未收录，请查看更新日志。";
    }

    static String recentText(String version, int limit) {
        if (limit <= 0) return "";
        StringBuilder result = new StringBuilder();
        int current = indexOf(version), count = 0;
        if (current < 0) {
            result.append(currentText(version));
            count++;
            current = HISTORY.length - 1;
        }
        for (int i = current; i >= 0 && count < Math.min(limit, 100); i--, count++) {
            if (result.length() > 0) result.append("\n\n");
            result.append(groupText(HISTORY[i]));
        }
        return result.toString();
    }

    private static int indexOf(String version) {
        String requested = version == null ? "" : version.trim();
        for (int i = HISTORY.length - 1; i >= 0; i--)
            if (requested.equals(versionOf(HISTORY[i]))) return i;
        return -1;
    }

    private static String versionOf(String[] group) {
        if (group == null || group.length == 0 || group[0] == null) return "";
        String title = group[0].trim();
        int space = title.indexOf(' ');
        return space < 0 ? title : title.substring(0, space);
    }

    private static String groupText(String[] group) {
        if (group == null || group.length == 0) return "";
        StringBuilder result = new StringBuilder(group[0]);
        for (int i = 1; i < group.length; i++) result.append("\n• ").append(group[i]);
        return result.toString();
    }
